/**
 * Builds the source of a bundled MCP stdio server: the plain-Node script an
 * agent's MCP client spawns, which speaks MCP JSON-RPC on stdin/stdout and
 * forwards every tool call to a host-owned bridge socket in Maestro main.
 *
 * Shared by Coworking (`maestro-coworking`) and Sketch Book (`maestro-sketch`)
 * so both servers carry ONE bridge client and ONE MCP stdio loop: the same
 * single shared connection, the same once-per-connection `hello` handshake
 * (identity from the spawn env, plus `ppid` for CLIs that drop that env), the
 * same per-RPC timeout, and the same protocol-version negotiation. Each server
 * supplies only its name, its env var names, its tool list, and the body of
 * its `callTool(name, args)`.
 *
 * The output is a self-contained CommonJS file that uses Node built-ins only,
 * so it runs under any system `node` or this Electron binary in Node mode.
 */

/** One tool as advertised in the MCP `tools/list` reply. */
export interface McpToolDefinition {
	name: string;
	description: string;
	inputSchema: Record<string, unknown>;
}

export interface McpStdioServerScriptOptions {
	/** Short name used in the header comment, e.g. `Coworking`. */
	title: string;
	/** MCP `serverInfo.name`, also the stderr log prefix, e.g. `maestro-coworking`. */
	serverName: string;
	/** Prefix of bridge error messages, e.g. `coworking bridge`. */
	bridgeLabel: string;
	/** Env var holding the spawning window's socket; preferred when set. */
	socketOverrideEnvVar: string;
	/** Env var holding the socket from the provider's MCP config entry. */
	socketEnvVar: string;
	/** Env var holding the owning agent's id, injected per spawn. */
	identityEnvVar: string;
	/** Name of the `hello` param that carries that id, e.g. `sessionId`. */
	identityParam: string;
	/** The tools advertised in `tools/list`. Emitted as JSON. */
	tools: ReadonlyArray<McpToolDefinition>;
	/**
	 * JavaScript source emitted at the top level of the script, after the bridge
	 * client. It MUST define `async function callTool(name, args)` that returns an
	 * MCP `tools/call` result (`{ content: [...] }`), or `null` for an unknown
	 * tool. It may call `bridgeCall(method, params, timeoutMs?)`, `jsonResult(value)`,
	 * and `BRIDGE_RPC_TIMEOUT_MS`.
	 */
	callToolSource: string;
	/** Default cap on one bridge RPC, in ms. */
	rpcTimeoutMs: number;
}

/** MCP protocol versions the bundled servers accept, newest first. */
export const MCP_SUPPORTED_PROTOCOL_VERSIONS = [
	'2025-11-25',
	'2025-06-18',
	'2025-03-26',
	'2024-11-05',
	'2024-10-07',
] as const;

const ENV_VAR_NAME = /^[A-Z_][A-Z0-9_]*$/;
const JS_IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function assertEnvVarName(value: string): void {
	if (!ENV_VAR_NAME.test(value)) throw new Error(`Invalid env var name: ${value}`);
}

/** Build the full source of an MCP stdio server script. */
export function buildMcpStdioServerScript(options: McpStdioServerScriptOptions): string {
	assertEnvVarName(options.socketOverrideEnvVar);
	assertEnvVarName(options.socketEnvVar);
	assertEnvVarName(options.identityEnvVar);
	if (!JS_IDENTIFIER.test(options.identityParam)) {
		throw new Error(`Invalid identity param: ${options.identityParam}`);
	}
	if (!Number.isInteger(options.rpcTimeoutMs) || options.rpcTimeoutMs <= 0) {
		throw new Error(`Invalid rpcTimeoutMs: ${options.rpcTimeoutMs}`);
	}

	const serverName = JSON.stringify(options.serverName);
	const logPrefix = JSON.stringify(`[${options.serverName}] `);
	const bridgeLabel = (suffix: string) => JSON.stringify(`${options.bridgeLabel}: ${suffix}`);
	const identityParam = options.identityParam;

	return `#!/usr/bin/env node
"use strict";
/**
 * Maestro ${options.title} - MCP stdio server.
 * AUTOGENERATED by Maestro. Do not edit; this file is overwritten on every Maestro launch.
 *
 * Speaks MCP JSON-RPC on stdin/stdout. Translates 'tools/list' and 'tools/call' into
 * IPC requests against the parent Maestro app via a Unix socket / named pipe.
 *
 * Spec: https://modelcontextprotocol.io/specification (subset).
 */
const net = require('net');

// Prefer the per-spawn override (${options.socketOverrideEnvVar}), injected by
// ProcessManager into the owning window's agent process so this subprocess binds
// to the bridge of the window that spawned it. Fall back to the shared user-level
// MCP config socket (a single global value, last install wins) for agent CLIs
// that do not propagate env to their MCP subprocess (e.g. Codex).
const SOCKET_PATH =
  process.env.${options.socketOverrideEnvVar} || process.env.${options.socketEnvVar};
if (!SOCKET_PATH) {
  process.stderr.write(${logPrefix} + '${options.socketEnvVar} env var is required\\n');
  process.exit(1);
}

// OWNER_ID identifies which Maestro agent owns this MCP subprocess. The fast
// path is env injection at agent-CLI spawn time, which works for any agent CLI
// that propagates parent env to its MCP subprocesses (Claude Code, OpenCode).
// For agent CLIs that do NOT propagate parent env (notably Codex), OWNER_ID is
// absent and the bridge falls back to PID-based resolution: we always include
// process.ppid in the hello payload and the bridge walks the process tree to
// find the owning agent. Unknown callers fail closed in the bridge, never here.
const OWNER_ID = process.env.${options.identityEnvVar} || null;

const SERVER_INFO = { name: ${serverName}, version: '1.0.0' };
// Listed newest-first. The MCP spec says: if the client requests a version we
// support, echo it back; otherwise pick one we do support. We pick the newest
// supported version as the fallback (also our preferred version when the client
// sends nothing). https://modelcontextprotocol.io/specification/.../basic/lifecycle
const SUPPORTED_PROTOCOL_VERSIONS = ${JSON.stringify(MCP_SUPPORTED_PROTOCOL_VERSIONS)};
const TOOLS = ${JSON.stringify(options.tools, null, 2)};

// ---------- Bridge client (lazy, single shared connection) ----------
let bridgeConn = null;
let bridgeBuffer = '';
let connectPromise = null;
let helloPromise = null;
const pending = new Map();
let nextRpcId = 1;
// Cap each in-flight RPC so a wedged-but-not-disconnected bridge can't stall
// tools/call indefinitely.
const BRIDGE_RPC_TIMEOUT_MS = ${options.rpcTimeoutMs};

function rejectAllPending(err) {
  for (const p of pending.values()) p.reject(err);
  pending.clear();
}

function connectBridge() {
  if (bridgeConn) return Promise.resolve(bridgeConn);
  // Concurrent callers must share a single in-flight connection so the module-
  // level bridgeBuffer doesn't get spliced across multiple sockets.
  if (connectPromise) return connectPromise;

  connectPromise = new Promise((resolve, reject) => {
    const c = net.createConnection({ path: SOCKET_PATH }, () => {
      c.setEncoding('utf8');
      // Reset shared buffer for this fresh connection.
      bridgeBuffer = '';
      c.on('data', (chunk) => {
        bridgeBuffer += chunk;
        let nl;
        while ((nl = bridgeBuffer.indexOf('\\n')) !== -1) {
          const line = bridgeBuffer.slice(0, nl).trim();
          bridgeBuffer = bridgeBuffer.slice(nl + 1);
          if (!line) continue;
          let msg;
          try {
            msg = JSON.parse(line);
          } catch {
            continue;
          }
          const p = pending.get(msg.id);
          if (!p) continue;
          pending.delete(msg.id);
          if (msg.error) p.reject(new Error(msg.error.message || ${bridgeLabel('error')}));
          else p.resolve(msg.result);
        }
      });
      c.on('error', (err) => {
        rejectAllPending(err);
        bridgeConn = null;
        helloPromise = null;
      });
      // Reject pending RPCs on a clean close too - otherwise their callers
      // would hang forever waiting for a reply that will never come.
      c.on('close', () => {
        rejectAllPending(new Error(${bridgeLabel('connection closed')}));
        bridgeConn = null;
        helloPromise = null;
      });
      bridgeConn = c;
      resolve(c);
    });
    c.once('error', reject);
  }).finally(() => {
    connectPromise = null;
  });
  return connectPromise;
}

// Send a single RPC against an already-open bridge connection. No handshake
// gating here - the gate lives in bridgeCall() so this primitive can also be
// used to perform the handshake itself.
function rpc(conn, method, params, timeoutMs) {
  const id = nextRpcId++;
  let timeoutHandle = null;
  const promise = new Promise((resolve, reject) => {
    timeoutHandle = setTimeout(() => {
      // Drop the pending entry first so the response (if it ever arrives) is a no-op.
      pending.delete(id);
      reject(new Error(${bridgeLabel('rpc timed out')}));
    }, timeoutMs || BRIDGE_RPC_TIMEOUT_MS);
    pending.set(id, {
      resolve: (value) => {
        if (timeoutHandle) clearTimeout(timeoutHandle);
        resolve(value);
      },
      reject: (err) => {
        if (timeoutHandle) clearTimeout(timeoutHandle);
        reject(err);
      },
    });
  });
  try {
    conn.write(JSON.stringify({ id, method, params }) + '\\n');
  } catch (err) {
    if (timeoutHandle) clearTimeout(timeoutHandle);
    pending.delete(id);
    throw err;
  }
  return promise;
}

// Perform the owner-binding handshake exactly once per connection. Cached on
// helloPromise so concurrent first callers share one in-flight handshake; the
// connect-close handlers reset it so a reconnect re-handshakes.
//
// We send the owner id when env propagation worked, and *always* send ppid so
// the bridge can fall back to walking the process tree when it didn't. The
// bridge prefers the id if both are present.
function bridgeHello(conn) {
  if (helloPromise) return helloPromise;
  const params = {};
  if (OWNER_ID) params.${identityParam} = OWNER_ID;
  if (typeof process.ppid === 'number' && process.ppid > 0) params.ppid = process.ppid;
  helloPromise = rpc(conn, 'hello', params).catch((err) => {
    helloPromise = null;
    throw err;
  });
  return helloPromise;
}

async function bridgeCall(method, params, timeoutMs) {
  // Capture the resolved socket locally so that if bridgeConn is nulled out
  // between the await and the write (e.g. by a synchronous error handler), we
  // either succeed or surface the failure immediately instead of leaking the
  // pending entry.
  const conn = bridgeConn || (await connectBridge());
  if (!conn || conn.destroyed) {
    throw new Error(${bridgeLabel('not connected')});
  }
  await bridgeHello(conn);
  return rpc(conn, method, params, timeoutMs);
}

/** A tools/call result carrying one pretty-printed JSON text block. */
function jsonResult(value) {
  return { content: [{ type: 'text', text: JSON.stringify(value, null, 2) }] };
}

// ---------- Tool calls (server specific) ----------
${options.callToolSource}

// ---------- MCP stdio framing ----------
let stdinBuffer = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
  stdinBuffer += chunk;
  let nl;
  while ((nl = stdinBuffer.indexOf('\\n')) !== -1) {
    const line = stdinBuffer.slice(0, nl).trim();
    stdinBuffer = stdinBuffer.slice(nl + 1);
    if (!line) continue;
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      continue;
    }
    handleMessage(msg).catch((err) => {
      process.stderr.write(${logPrefix} + 'handler error: ' + String(err) + '\\n');
    });
  }
});

function send(msg) {
  process.stdout.write(JSON.stringify(msg) + '\\n');
}

function rpcResult(id, result) {
  return { jsonrpc: '2.0', id, result };
}
function rpcError(id, code, message) {
  return { jsonrpc: '2.0', id, error: { code, message } };
}

async function handleMessage(msg) {
  // Notifications: no id, no response.
  if (msg.id === undefined || msg.id === null) {
    // 'notifications/initialized' and others - ignore.
    return;
  }
  const { id, method, params } = msg;
  try {
    if (method === 'initialize') {
      const requested = params && params.protocolVersion;
      const protocolVersion =
        typeof requested === 'string' && SUPPORTED_PROTOCOL_VERSIONS.indexOf(requested) !== -1
          ? requested
          : SUPPORTED_PROTOCOL_VERSIONS[0];
      send(
        rpcResult(id, {
          protocolVersion,
          serverInfo: SERVER_INFO,
          capabilities: { tools: {} },
        })
      );
      return;
    }
    if (method === 'ping') {
      send(rpcResult(id, {}));
      return;
    }
    if (method === 'tools/list') {
      send(rpcResult(id, { tools: TOOLS }));
      return;
    }
    if (method === 'tools/call') {
      const name = params && params.name;
      const args = (params && params.arguments) || {};
      const result = await callTool(name, args);
      if (result === null) {
        send(rpcError(id, -32601, 'Unknown tool: ' + String(name)));
        return;
      }
      send(rpcResult(id, result));
      return;
    }
    send(rpcError(id, -32601, 'Unknown method: ' + String(method)));
  } catch (err) {
    send(rpcError(id, -32000, err && err.message ? err.message : String(err)));
  }
}

// Keep stdin alive so the agent's MCP client controls our lifecycle.
process.stdin.on('end', () => process.exit(0));
process.on('SIGINT', () => process.exit(0));
process.on('SIGTERM', () => process.exit(0));
`;
}
